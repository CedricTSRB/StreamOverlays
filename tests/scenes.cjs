const {chromium}=require('playwright');
const assert=require('node:assert/strict');
(async()=>{
 const browser=await chromium.launch({headless:true,args:['--no-sandbox','--disable-dev-shm-usage']});
 const context=await browser.newContext({viewport:{width:1440,height:1000},permissions:['clipboard-read','clipboard-write']});
 const page=await context.newPage();const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto(process.env.TEST_URL||'http://127.0.0.1:8765/');
 await page.locator('[data-nav="stream-scenes"]').click();
 await assert.equal(await page.locator('#stream-scenes').isVisible(),true);
 assert.equal(await page.locator('.ss-mode-card').count(),3);
 assert.equal(await page.locator('.ss-pack').count(),24);
 assert.equal(await page.locator('.ss-trio-item').count(),3);
 assert.equal(await page.locator('.ss-screen').first().evaluate(e=>getComputedStyle(e).aspectRatio),'16 / 9');
 await page.locator('[data-scene-type="brb"]').click();
 assert.equal(await page.locator('#ss-current-title').textContent(),'Be Right Back');
 assert.equal(await page.locator('.ss-mode-card.is-selected').count(),1);
 assert.equal(await page.locator('#ss-feature-preview h2').textContent(),'BE RIGHT BACK');
 await page.locator('.ss-pack[data-pack="8"]').click();
 assert.equal(await page.locator('#ss-pack-title').textContent(),'Golden Stars');
 assert.equal(await page.locator('.ss-pack.is-selected').count(),1);
 await page.locator('#ss-name').fill('MEIN STREAM');
 assert.equal(await page.locator('#ss-feature-preview .ss-channel').textContent(),'MEIN STREAM');
 assert.equal(await page.locator('.ss-trio-item .ss-channel').first().textContent(),'MEIN STREAM');
 await page.locator('#ss-copy').click();const link=await page.evaluate(()=>navigator.clipboard.readText());
 assert(link.includes('overlay=scene')&&link.includes('config='));
 const obs=await browser.newPage({viewport:{width:1920,height:1080}});await obs.goto(link);
 assert.equal(await obs.locator('.ss-obs-canvas h2').textContent(),'BE RIGHT BACK');
 assert.equal(await obs.locator('.ss-obs-canvas .ss-channel').textContent(),'MEIN STREAM');
 assert.equal(await obs.locator('.sidebar').isVisible(),false);
 await obs.close();
 await page.reload();await page.locator('[data-nav="stream-scenes"]').click();
 assert.equal(await page.locator('#ss-pack-title').textContent(),'Golden Stars');
 await page.setViewportSize({width:390,height:844});
 assert.equal(await page.locator('.ss-mode-card').count(),3);
 assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'mobile horizontal overflow');
 assert.deepEqual(errors,[]);
 await browser.close();console.log('PASS: 3 visual scene selectors, 24 designs, 3 previews, OBS links, persistence, mobile');
})().catch(e=>{console.error(e);process.exit(1)});
